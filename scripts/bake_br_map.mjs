// Bakes the battle-royale walk/line-of-sight grid of the quartiere into shared/br_map.mjs (used by shared/br.mjs on the
// server and in the browser). Source: src/quartiere/layout.js (pure data). Run: node scripts/bake_br_map.mjs
// Cell = 1 m. '1' = open ground (outdoor zones: streets, porticoes, piazzetta, Petroni, checkpoint, meadow),
// '0' = blocked (buildings, interiors, the garden/house, the calcetto cage, outside the map).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ZONES, BUILDINGS, PITCH, BOUNDS, ST, PET } from '../src/quartiere/layout.js';
import { NORD_ZONES, nordColliders } from '../src/quartiere/nord_layout.js'; // the northern districts (Voltone, Via Zamboni, Piazza Verdi, Via Rizzoli, Piazza Maggiore)

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const X0 = Math.floor(BOUNDS.x0), Z0 = 0, X1 = Math.ceil(BOUNDS.x1), Z1 = Math.ceil(BOUNDS.z1);
const W = X1 - X0, H = Z1 - Z0;
const g = new Uint8Array(W * H);
const inRect = (x, z, r) => x >= r[0] && x <= r[2] && z >= r[1] && z <= r[3];
const outdoor = ZONES.filter(z => !z.indoor).concat(NORD_ZONES.filter(n => !ZONES.some(z => z.name === n.name)));
const NC = nordColliders().C; // buildings' ground floors, arcade columns, Nettuno, furniture, district edges
// building footprints (porticoes stay open: far row facade at z=ST.zFar, Petroni facades at x=PET.x0 / PET.x1)
const foot = BUILDINGS.map(b => {
  let [x0, z0, x1, z1] = b.rect;
  if (b.portico && b.face === 's') z0 = Math.max(z0, ST.zFar);
  if (b.portico && b.face === 'e') x1 = Math.min(x1, PET.x0);
  if (b.portico && b.face === 'w') x0 = Math.max(x0, PET.x1);
  return b.passage ? [[x0, z0, b.passage.x0, z1], [b.passage.x1, z0, x1, z1]] : [[x0, z0, x1, z1]]; // the Voltone stays open
}).flat();
let open = 0;
for (let j = 0; j < H; j++) for (let i = 0; i < W; i++) {
  const x = X0 + i + 0.5, z = Z0 + j + 0.5;
  let ok = outdoor.some(zn => inRect(x, z, zn.rect));
  if (ok && foot.some(r => inRect(x, z, [r[0] - 0.2, r[1] - 0.2, r[2] + 0.2, r[3] + 0.2]))) ok = false;
  if (ok && inRect(x, z, [PITCH.x0 - 0.6, PITCH.z0 - 0.6, PITCH.x1 + 0.6, PITCH.z1 + 0.6])) ok = false;
  if (ok) for (const c of NC) { if (c.type === 'box' ? inRect(x, z, [c.min[0] - 0.2, c.min[1] - 0.2, c.max[0] + 0.2, c.max[1] + 0.2]) : (c.r >= 0.3 && Math.hypot(x - c.c[0], z - c.c[1]) < Math.max(0.5, c.r))) { ok = false; break; } }
  // portico columns: one blocked cell every bay on the column line (keeps LOS honest under the arcades)
  if (ok && Math.abs(z - (ST.colZ + 0.5)) < 0.5 && x > ST.x0 && x < ST.x1 && (Math.floor(x - ST.x0) % 4 === 0)) ok = false;
  g[j * W + i] = ok ? 1 : 0; if (ok) open++;
}
// run-length rows: "1:12,0:3,…" per row is overkill; a plain 0/1 string per row compresses fine in the bundle
const rows = []; for (let j = 0; j < H; j++) { let s = ''; for (let i = 0; i < W; i++) s += g[j * W + i]; rows.push(s); }
const out = `// GENERATED by scripts/bake_br_map.mjs from src/quartiere/layout.js + nord_layout.js — do not edit by hand.
// Battle royale grid of the quartiere: 1 m cells, x from ${X0}, z from ${Z0}; rows[j][i] = '1' open, '0' blocked.
export const BR_MAP = { x0: ${X0}, z0: ${Z0}, w: ${W}, h: ${H}, open: ${open}, rows: ${JSON.stringify(rows)} };
`;
fs.writeFileSync(path.join(ROOT, 'shared', 'br_map.mjs'), out);
console.log(`br_map: ${W}x${H} cells, ${open} open (${Math.round(open / (W * H) * 100)}%) -> shared/br_map.mjs (${(out.length / 1024).toFixed(1)} KB)`);
