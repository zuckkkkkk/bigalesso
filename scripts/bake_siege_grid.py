# Bakes the coarse walk grid of the quartiere for the "Assedio" RTS (shared/siege_grid.mjs) from the running game:
# level.isWalkable (all colliders: buildings, porticoes, fences, benches, trees, cage…) sampled on a 0.5 m grid.
# A cell is walkable only if its centre and 4 inset points are (thin fences/walls become solid, the 1.4 m garden
# gate stays open). Usage: python3 scripts/bake_siege_grid.py http://127.0.0.1:8204/index.html
# (needs a served build; run with `flock /tmp/chrome.lock` when other browsers may be running)
import asyncio, sys, json, base64, os
from playwright.async_api import async_playwright
URL = sys.argv[1] if len(sys.argv) > 1 else 'http://127.0.0.1:8204/index.html'
OUT = os.path.join(os.path.dirname(__file__), '..', 'shared', 'siege_grid.mjs')
X0, Z0, CELL, W, H = -96, 0, 0.5, 316, 216  # layout BOUNDS: x -96..62, z 0..108 (with the northern districts)
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(args=['--use-angle=swiftshader', '--enable-unsafe-swiftshader'])
        pg = await b.new_page(viewport={'width': 640, 'height': 360})
        await pg.goto(URL + '?auto=1&skip=1', wait_until='domcontentloaded')
        await pg.wait_for_function('window.__app && window.__app.level && window.__gfx && window.__gfx.ready', timeout=300000, polling=1000)
        await pg.wait_for_timeout(1500)
        arr = await pg.evaluate(f'''(() => {{
          const L = window.__app.level, X0 = {X0}, Z0 = {Z0}, C = {CELL}, W = {W}, H = {H}, out = new Array(Math.ceil(W * H / 8)).fill(0);
          const ok = (x, z) => L.isWalkable(x, z, 0.04);
          for (let j = 0; j < H; j++) for (let i = 0; i < W; i++) {{
            const x = X0 + (i + 0.5) * C, z = Z0 + (j + 0.5) * C, d = C * 0.4;
            if (ok(x, z) && ok(x - d, z - d) && ok(x + d, z - d) && ok(x - d, z + d) && ok(x + d, z + d)) {{ const k = j * W + i; out[k >> 3] |= 1 << (k & 7); }}
          }}
          return out;
        }})()''')
        await b.close()
    raw = bytes(arr)
    n = sum(bin(v).count('1') for v in raw)
    b64 = base64.b64encode(raw).decode()
    with open(OUT, 'w') as f:
        f.write('// Walk grid of the quartiere for the siege RTS (shared/siege.mjs). GENERATED by scripts/bake_siege_grid.py\n')
        f.write('// from level.isWalkable: bit (j*w+i) = 1 if the 0.5 m cell at x0+(i+.5)*cell, z0+(j+.5)*cell is walkable.\n')
        f.write(f'export const GRID = {{ x0: {X0}, z0: {Z0}, cell: {CELL}, w: {W}, h: {H}, walkable: {n}, b64: \'{b64}\' }};\n')
    print('walkable cells', n, 'of', W * H, '->', OUT, len(b64), 'chars')
asyncio.run(main())
