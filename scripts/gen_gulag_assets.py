# Generates src/gulag_assets.js: small textures (data URIs) for the Gulag easter egg, cut from assets/news/*.jpg
import base64, io
from PIL import Image
def enc(path, size, q=72, crop=None):
    im = Image.open(path).convert('RGB')
    if crop: im = im.crop(crop)
    im.thumbnail(size, Image.LANCZOS)
    b = io.BytesIO(); im.save(b, 'JPEG', quality=q, optimize=True, progressive=True)
    return 'data:image/jpeg;base64,' + base64.b64encode(b.getvalue()).decode(), im.size, len(b.getvalue())
items = {
  'processo': ('assets/news/x-014.jpg', (420, 630), None),   # poster "Il Processo del Secolo"
  'giudice': ('assets/news/x-013.jpg', (300, 375), None),    # judge portrait
  'suite': ('assets/news/x-022.jpg', (512, 512), None),      # Gulag Suite ad
  'ghiaccio': ('assets/news/x-005.jpg', (360, 360), None),   # Ghiaccio del Gulag ad
  'aula': ('assets/news/x-012.jpg', (512, 342), None),       # the trial (TV)
}
out = ['// generated by scripts/gen_gulag_assets.py: images from the Corriere delle Due Torri n.313 (goliardic paper)']
tot = 0
for k, (p, s, c) in items.items():
    uri, sz, n = enc(p, s, crop=c); tot += n
    out.append(f"export const {k.upper()} = {{ url: '{uri}', w: {sz[0]}, h: {sz[1]} }};")
open('src/gulag_assets.js', 'w').write('\n'.join(out) + '\n')
print('ok', tot // 1024, 'KB')
