// node scripts/gen_quiz_data.mjs — writes shared/quiz_data.mjs from assets/chat/quotes.json + personas.json, so the
// server referee of the online "Chi l'ha detto?" (shared/quiz.mjs) has the same quotes as the browser (the server image
// ships only shared/ and server/). Same filter as src/minigames/shared.js quotes(). test/quiz_rules.mjs checks it is in sync.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const rd = f => JSON.parse(fs.readFileSync(path.join(ROOT, 'assets', 'chat', f), 'utf8'));
const arr = x => Array.isArray(x) ? x : Object.values(x || {});
export function build() {
  const ids = arr(rd('personas.json')).filter(p => p && p.id).map(p => p.id);
  const set = new Set(ids);
  const q = arr(rd('quotes.json')).filter(x => x && x.who && x.text && set.has(x.who) && x.text.length >= 6 && x.text.length <= 110).map(x => [x.who, x.text]);
  return { ids, q };
}
export function source({ ids, q }) {
  return '// GENERATED by scripts/gen_quiz_data.mjs from assets/chat/quotes.json + personas.json — do not edit by hand.\n' +
    '// The filtered group quotes (who, text) for the online "Chi l\'ha detto?" (shared/quiz.mjs).\n' +
    'export const PERSONA_IDS = ' + JSON.stringify(ids) + ';\n' +
    'export const QUOTES = [\n' + q.map(x => '  ' + JSON.stringify(x) + ',').join('\n') + '\n];\n';
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const d = build(); fs.writeFileSync(path.join(ROOT, 'shared', 'quiz_data.mjs'), source(d));
  console.log('shared/quiz_data.mjs:', d.q.length, 'citazioni,', d.ids.length, 'personaggi');
}
