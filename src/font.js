const cache = new Map();
function glyphCanvas(ch, color) {
  const key = ch + color; if (cache.has(key)) return cache.get(key);
  const g = G[ch] || G['?'];
  const c = document.createElement('canvas'); c.width = 5; c.height = 7;
  const x = c.getContext('2d'); x.fillStyle = color;
  for (let r = 0; r < 7; r++) for (let b = 0; b < 5; b++) if (g[r] & (16 >> b)) x.fillRect(b, r, 1, 1);
  cache.set(key, c); return c;
}
export function textWidth(s, scale = 1) { return s.length * 6 * scale - scale; }
export function drawText(ctx, s, x, y, color = '#fff', scale = 1, align = 'left', shadow = '#000') {
  s = String(s).toUpperCase().replace(/[àá]/g, 'À').replace(/[èé]/g, 'È').replace(/[ìí]/g, 'Ì').replace(/[òó]/g, 'Ò').replace(/[ùú]/g, 'Ù');
  const w = textWidth(s, scale);
  if (align === 'center') x -= Math.floor(w / 2); else if (align === 'right') x -= w;
  x = Math.round(x); y = Math.round(y);
  for (let i = 0; i < s.length; i++) {
    const ch = s[i]; if (ch === ' ') continue;
    if (shadow) ctx.drawImage(glyphCanvas(ch, shadow), x + i * 6 * scale + scale, y + scale, 5 * scale, 7 * scale);
    ctx.drawImage(glyphCanvas(ch, color), x + i * 6 * scale, y, 5 * scale, 7 * scale);
  }
}
